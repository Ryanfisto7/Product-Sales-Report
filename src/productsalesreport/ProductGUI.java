  private void executeProcess() throws IOException {
        try {
            String name = txtCustomerName.getText();
            String prod = cmbProduct.getSelectedItem().toString();
            double p = Double.parseDouble(txtPrice.getText());

            ProductCalculations calc = new ProductCalculations(p);
            double v = calc.GetVat();
            double c = calc.GetCommission();
            double t = calc.GetTotal();

            javax.swing.JOptionPane.showMessageDialog(this, 
                "Customer Name: " + name + "\n" +
                "Product: " + prod + "\n" +
                "VAT: R " + v + "\n" +
                "COMMISSION: R " + c + "\n" +
                "TOTAL: R " + t);

            try (java.io.PrintWriter out = new java.io.PrintWriter(new java.io.FileWriter("data.txt", true))) {
                out.println("DATA LOG");
                out.println("****************************************");
                out.println("Customer Name: " + name);
                out.println("Product: " + prod);
                out.println("VAT: R " + v);
                out.println("COMMISSION: R " + c);
                out.println("TOTAL: R " + t);
                out.println("****************************************\n");
            }
        } catch (HeadlessException | NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Check inputs.");
        }
    }

